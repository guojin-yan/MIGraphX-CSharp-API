[CmdletBinding()]
param(
    [string] $HeaderPath,
    [switch] $AcquireHeader,
    [switch] $Verify
)

. (Join-Path $PSScriptRoot 'common.ps1')
$root = Get-RepositoryRoot
$manifestPath = Join-Path $root 'compatibility\m2-binding-subset.json'
$manifest = Get-Content -Raw -LiteralPath $manifestPath | ConvertFrom-Json

if ($AcquireHeader) {
    if (-not $HeaderPath) {
        $HeaderPath = Join-Path $root '.cache\m1\migraphx.h'
    }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $HeaderPath) | Out-Null
    Invoke-WebRequest -Uri $manifest.source.headerUrl -OutFile $HeaderPath
}

if (-not $HeaderPath) {
    throw 'Specify -HeaderPath or use -AcquireHeader.'
}
$HeaderPath = (Resolve-Path -LiteralPath $HeaderPath).Path
$actualHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $HeaderPath).Hash.ToLowerInvariant()
if ($actualHash -ne $manifest.source.headerSha256) {
    throw "Frozen header SHA-256 mismatch. Expected $($manifest.source.headerSha256), got $actualHash."
}
if ((Get-Item -LiteralPath $HeaderPath).Length -ne $manifest.source.headerByteLength) {
    throw 'Frozen header byte length does not match the manifest.'
}

function Normalize-CDeclaration([string] $value) {
    return ([regex]::Replace($value, '\s+', ' ')).Trim()
}

$normalizedHeader = Normalize-CDeclaration (Get-Content -Raw -LiteralPath $HeaderPath)
foreach ($handle in $manifest.handles) {
    if (-not $normalizedHeader.Contains((Normalize-CDeclaration $handle.cDeclaration))) {
        throw "Handle declaration is absent from the frozen header: $($handle.cDeclaration)"
    }
}
foreach ($function in $manifest.functions) {
    if (-not $normalizedHeader.Contains((Normalize-CDeclaration $function.cDeclaration))) {
        throw "Function declaration is absent from the frozen header: $($function.cDeclaration)"
    }
}

$banner = @"
// <auto-generated />
// Source: compatibility/m2-binding-subset.json
// Frozen migraphx.h SHA-256: $($manifest.source.headerSha256)
// Regenerate with eng/generate-interop.ps1; do not edit by hand.
"@

$common = [Text.StringBuilder]::new()
[void]$common.AppendLine($banner)
[void]$common.AppendLine('using System;')
[void]$common.AppendLine()
[void]$common.AppendLine('namespace JYPPX.ROCm.MIGraphXSharp.Interop;')
[void]$common.AppendLine()
[void]$common.AppendLine()
foreach ($enum in $manifest.enums) {
    [void]$common.AppendLine("internal enum $($enum.managedName)")
    [void]$common.AppendLine('{')
    foreach ($value in $enum.values) {
        [void]$common.AppendLine("    $($value.managedName) = $($value.value),")
    }
    [void]$common.AppendLine('}')
    [void]$common.AppendLine()
}
[void]$common.AppendLine('internal static partial class NativeMethods')
[void]$common.AppendLine('{')
[void]$common.AppendLine("    internal const string LibraryName = `"$($manifest.nativeLibrary.logicalName)`";")
[void]$common.AppendLine('    internal static readonly string[] M1RequiredExports =')
[void]$common.AppendLine('    {')
foreach ($function in @($manifest.functions | Select-Object -First $manifest.scope.m1FunctionCount)) {
    [void]$common.AppendLine("        `"$($function.cName)`",")
}
[void]$common.AppendLine('    };')
[void]$common.AppendLine()
[void]$common.AppendLine('    internal static readonly string[] M2RequiredExports =')
[void]$common.AppendLine('    {')
foreach ($function in $manifest.functions) {
    [void]$common.AppendLine("        `"$($function.cName)`",")
}
[void]$common.AppendLine('    };')
[void]$common.AppendLine('}')

function Get-ManagedParameters($function) {
    $keywords = @('abstract','as','base','bool','break','byte','case','catch','char','checked','class','const','continue','decimal','default','delegate','do','double','else','enum','event','explicit','extern','false','finally','fixed','float','for','foreach','goto','if','implicit','in','int','interface','internal','is','lock','long','namespace','new','null','object','operator','out','override','params','private','protected','public','readonly','ref','return','sbyte','sealed','short','sizeof','stackalloc','static','string','struct','switch','this','throw','true','try','typeof','uint','ulong','unchecked','unsafe','ushort','using','virtual','void','volatile','while')
    $parts = foreach ($parameter in $function.parameters) {
        $modifierProperty = $parameter.PSObject.Properties['managedModifier']
        $modifier = if ($null -ne $modifierProperty) { "$($modifierProperty.Value) " } else { '' }
        $name = if ($parameter.cName -in $keywords) { "@$($parameter.cName)" } else { $parameter.cName }
        "$modifier$($parameter.managedType) $name"
    }
    return $parts -join ', '
}

$libraryImport = [Text.StringBuilder]::new()
[void]$libraryImport.AppendLine($banner)
[void]$libraryImport.AppendLine('#if MIGRAPHX_LIBRARYIMPORT_PATH')
[void]$libraryImport.AppendLine('using System;')
[void]$libraryImport.AppendLine('using System.Runtime.CompilerServices;')
[void]$libraryImport.AppendLine('using System.Runtime.InteropServices;')
[void]$libraryImport.AppendLine()
[void]$libraryImport.AppendLine('namespace JYPPX.ROCm.MIGraphXSharp.Interop;')
[void]$libraryImport.AppendLine()
[void]$libraryImport.AppendLine('internal static partial class NativeMethods')
[void]$libraryImport.AppendLine('{')
foreach ($function in $manifest.functions) {
    [void]$libraryImport.AppendLine("    [LibraryImport(LibraryName, EntryPoint = `"$($function.cName)`")]")
    [void]$libraryImport.AppendLine('    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]')
    [void]$libraryImport.AppendLine("    internal static partial NativeMIGraphXStatus $($function.managedName)($(Get-ManagedParameters $function));")
    [void]$libraryImport.AppendLine()
}
[void]$libraryImport.AppendLine('}')
[void]$libraryImport.AppendLine('#endif')

$dllImport = [Text.StringBuilder]::new()
[void]$dllImport.AppendLine($banner)
[void]$dllImport.AppendLine('#if MIGRAPHX_DLLIMPORT_PATH')
[void]$dllImport.AppendLine('using System;')
[void]$dllImport.AppendLine('using System.Runtime.InteropServices;')
[void]$dllImport.AppendLine()
[void]$dllImport.AppendLine('namespace JYPPX.ROCm.MIGraphXSharp.Interop;')
[void]$dllImport.AppendLine()
[void]$dllImport.AppendLine('internal static partial class NativeMethods')
[void]$dllImport.AppendLine('{')
foreach ($function in $manifest.functions) {
    [void]$dllImport.AppendLine("    [DllImport(LibraryName, EntryPoint = `"$($function.cName)`", CallingConvention = CallingConvention.Cdecl)]")
    [void]$dllImport.AppendLine("    internal static extern NativeMIGraphXStatus $($function.managedName)($(Get-ManagedParameters $function));")
    [void]$dllImport.AppendLine()
}
[void]$dllImport.AppendLine('}')
[void]$dllImport.AppendLine('#endif')

$outputs = [ordered]@{
    'NativeMethods.g.cs' = $common.ToString()
    'NativeMethods.LibraryImport.g.cs' = $libraryImport.ToString()
    'NativeMethods.DllImport.g.cs' = $dllImport.ToString()
}
$generatedDirectory = Join-Path $root 'src\JYPPX.ROCm.MIGraphX.CSharp.API\Generated'

foreach ($entry in $outputs.GetEnumerator()) {
    $path = Join-Path $generatedDirectory $entry.Key
    $expected = $entry.Value.Replace("`r`n", "`n")
    if ($Verify) {
        if (-not (Test-Path -LiteralPath $path)) {
            throw "Generated output is missing: $path"
        }
        $actual = (Get-Content -Raw -LiteralPath $path).Replace("`r`n", "`n")
        if ($actual -ne $expected) {
            throw "Generated output drifted: $path"
        }
    }
    else {
        [IO.File]::WriteAllText($path, $expected, [Text.UTF8Encoding]::new($false))
    }
}

Write-Output "M2 interop generation $($(if ($Verify) { 'verification' } else { 'update' })) passed for $actualHash."
