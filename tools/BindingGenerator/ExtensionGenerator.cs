using System.Text;
using System.Text.Json;

namespace JYPPX.ROCm.MIGraphXSharp.BindingGenerator;

// The historical 2.15 baseline remains unchanged. Optional 2.18 entry points are
// generated from the separately pinned Windows header, including only reviewed additions.
internal static class ExtensionGenerator
{
    internal const string HeaderSha256 = "bc5799f1c452e5d1e674092499f24bb3ff0b3b32b2fac3d8fe8638243ad60466";
    internal static void Generate(string headerPath, string preprocessedPath, string outputDirectory)
    {
        var hash = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(headerPath))).ToLowerInvariant();
        if (hash != HeaderSha256) throw new InvalidDataException("MIGraphX 2.18 header hash mismatch: " + hash);
        var parsed = CHeaderParser.Parse(File.ReadAllText(preprocessedPath), File.ReadAllText(headerPath));
        var names = new HashSet<string>(StringComparer.Ordinal)
        {
            "symbol_bounds_destroy", "symbol_bounds_assign_to", "symbol_bounds_create", "symbol_bounds_add",
            "dynamic_dimension_create_symbolic", "dynamic_dimension_is_symbolic", "target_create_with_options",
            "trace_info_destroy", "trace_info_assign_to", "trace_info_create", "trace_info_get_index",
            "trace_info_get_name", "trace_info_get_result", "program_run_trace",
            "onnx_options_set_use_debug_symbols", "onnx_options_set_dim_param",
            "compile_options_set_compile_mode", "compile_options_set_advance_backend_options",
        }.Select(name => "migraphx_" + name).ToHashSet(StringComparer.Ordinal);
        var functions = parsed.Functions.Where(function => names.Contains(function.Name)).ToArray();
        if (functions.Length != names.Count) throw new InvalidDataException("The 18 reviewed 2.18 extensions were not found.");
        var source = new StringBuilder("// <auto-generated />\n// MIGraphX 2.18 optional extensions; generated by tools/BindingGenerator.\n// Header SHA-256: " + hash + "\nusing System;\nusing System.Runtime.InteropServices;\n#if MIGRAPHX_LIBRARYIMPORT_PATH\nusing System.Runtime.CompilerServices;\n#endif\n\nnamespace JYPPX.ROCm.MIGraphXSharp.Interop;\n\ninternal static partial class NativeMethods\n{\n");
        foreach (var function in functions)
        {
            var name = string.Concat(function.Name[9..].Split('_').Select(part => char.ToUpperInvariant(part[0]) + part[1..]));
            // The two varargs APIs accept fully materialized JSON only. Callers escape
            // percent signs; no managed varargs or caller-supplied format arguments exist.
            var parameters = string.Join(", ", function.Parameters.Where(parameter => parameter.BaseType != "...")
                .Select((parameter, index) => BindingGenerator.MapManagedType(parameter) + " p" + index));
            source.AppendLine("#if MIGRAPHX_LIBRARYIMPORT_PATH")
                .AppendLine($"    [LibraryImport(LibraryName, EntryPoint = \"{function.Name}\")]")
                .AppendLine("    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]")
                .AppendLine($"    internal static partial NativeMIGraphXStatus {name}({parameters});")
                .AppendLine("#else")
                .AppendLine($"    [DllImport(LibraryName, EntryPoint = \"{function.Name}\", CallingConvention = CallingConvention.Cdecl)]")
                .AppendLine($"    internal static extern NativeMIGraphXStatus {name}({parameters});")
                .AppendLine("#endif");
        }
        source.AppendLine("}");
        Directory.CreateDirectory(outputDirectory);
        File.WriteAllText(Path.Combine(outputDirectory, "NativeMethods.Extensions218.g.cs"), source.ToString().Replace("\r\n", "\n").Replace("\n", "\r\n"), new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(outputDirectory, "native-extensions-2.18.json"), JsonSerializer.Serialize(new
        {
            version = "2.18", headerSha256 = hash,
            functions = functions.Select(function => new { function.Name, function.CanonicalDeclaration }),
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n", new UTF8Encoding(false));
    }
}
